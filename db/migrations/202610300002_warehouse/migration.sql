-- Analytical star schema. The operational public schema is only read by ETL.
CREATE SCHEMA "dw";

CREATE TABLE dw.dim_gestion (
  gestion_id integer PRIMARY KEY,
  nombre varchar(30) NOT NULL,
  fecha_inicio date NOT NULL,
  fecha_fin date NOT NULL,
  CONSTRAINT dim_gestion_fechas CHECK(fecha_fin>=fecha_inicio)
);
CREATE TABLE dw.dim_carrera (
  carrera_id integer PRIMARY KEY,
  codigo varchar(20) NOT NULL,
  nombre varchar(120) NOT NULL,
  nivel varchar(50) NOT NULL,
  regimen varchar(32) NOT NULL
);
CREATE TABLE dw.dim_estudiante (
  estudiante_id integer PRIMARY KEY,
  registro varchar(20) NOT NULL,
  nombres varchar(80) NOT NULL,
  apellidos varchar(100) NOT NULL
);
CREATE TABLE dw.dim_docente (
  docente_id integer PRIMARY KEY,
  nombres varchar(80) NOT NULL,
  apellidos varchar(100) NOT NULL,
  especialidad varchar(120) NOT NULL
);
CREATE TABLE dw.dim_materia (
  materia_id integer PRIMARY KEY,
  carrera_id integer NOT NULL REFERENCES dw.dim_carrera(carrera_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  codigo varchar(20) NOT NULL,
  nombre varchar(120) NOT NULL,
  nivel_curso integer NOT NULL
);
CREATE INDEX dim_materia_carrera_idx ON dw.dim_materia(carrera_id);
CREATE TABLE dw.dim_tiempo (
  fecha date PRIMARY KEY,
  anio integer NOT NULL,
  mes integer NOT NULL CHECK(mes BETWEEN 1 AND 12),
  dia integer NOT NULL CHECK(dia BETWEEN 1 AND 31),
  trimestre integer NOT NULL CHECK(trimestre BETWEEN 1 AND 4),
  dia_semana integer NOT NULL CHECK(dia_semana BETWEEN 1 AND 7),
  mes_nombre varchar(20) NOT NULL
);
CREATE TABLE dw.fact_matriculas (
  matricula_id integer PRIMARY KEY,
  gestion_id integer NOT NULL REFERENCES dw.dim_gestion(gestion_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  carrera_id integer NOT NULL REFERENCES dw.dim_carrera(carrera_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  estudiante_id integer NOT NULL REFERENCES dw.dim_estudiante(estudiante_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  fecha date NOT NULL REFERENCES dw.dim_tiempo(fecha) ON DELETE NO ACTION ON UPDATE NO ACTION,
  estado varchar(32) NOT NULL,
  cantidad integer NOT NULL DEFAULT 1 CHECK(cantidad=1)
);
CREATE INDEX fact_matriculas_gestion_carrera_idx ON dw.fact_matriculas(gestion_id,carrera_id);
CREATE INDEX fact_matriculas_estudiante_idx ON dw.fact_matriculas(estudiante_id);
CREATE INDEX fact_matriculas_fecha_idx ON dw.fact_matriculas(fecha);
CREATE TABLE dw.fact_resultados (
  inscripcion_id integer PRIMARY KEY,
  matricula_id integer NOT NULL,
  gestion_id integer NOT NULL REFERENCES dw.dim_gestion(gestion_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  carrera_id integer NOT NULL REFERENCES dw.dim_carrera(carrera_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  estudiante_id integer NOT NULL REFERENCES dw.dim_estudiante(estudiante_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  docente_id integer NOT NULL REFERENCES dw.dim_docente(docente_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  materia_id integer NOT NULL REFERENCES dw.dim_materia(materia_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  fecha date NOT NULL REFERENCES dw.dim_tiempo(fecha) ON DELETE NO ACTION ON UPDATE NO ACTION,
  promedio decimal(8,5) NOT NULL,
  asistencia decimal(8,5) NOT NULL,
  nota_final decimal(8,5) NOT NULL,
  resultado varchar(32) NOT NULL,
  aprobado integer NOT NULL CHECK(aprobado IN(0,1)),
  recuperacion integer NOT NULL CHECK(recuperacion IN(0,1))
);
CREATE INDEX fact_resultados_gestion_carrera_idx ON dw.fact_resultados(gestion_id,carrera_id);
CREATE INDEX fact_resultados_materia_idx ON dw.fact_resultados(materia_id);
CREATE INDEX fact_resultados_docente_idx ON dw.fact_resultados(docente_id);
CREATE INDEX fact_resultados_estudiante_idx ON dw.fact_resultados(estudiante_id);
CREATE INDEX fact_resultados_fecha_idx ON dw.fact_resultados(fecha);
CREATE TABLE dw.fact_pagos (
  pago_id integer PRIMARY KEY,
  matricula_id integer NOT NULL,
  cargo_id integer NOT NULL,
  gestion_id integer NOT NULL REFERENCES dw.dim_gestion(gestion_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  carrera_id integer NOT NULL REFERENCES dw.dim_carrera(carrera_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  estudiante_id integer NOT NULL REFERENCES dw.dim_estudiante(estudiante_id) ON DELETE NO ACTION ON UPDATE NO ACTION,
  fecha date NOT NULL REFERENCES dw.dim_tiempo(fecha) ON DELETE NO ACTION ON UPDATE NO ACTION,
  monto decimal(10,2) NOT NULL CHECK(monto>0),
  metodo varchar(32) NOT NULL,
  recibo varchar(30) NOT NULL
);
CREATE INDEX fact_pagos_gestion_carrera_idx ON dw.fact_pagos(gestion_id,carrera_id);
CREATE INDEX fact_pagos_fecha_idx ON dw.fact_pagos(fecha);
CREATE INDEX fact_pagos_estudiante_idx ON dw.fact_pagos(estudiante_id);
CREATE TABLE dw.etl_ejecuciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inicio timestamp(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fin timestamp(3),
  estado varchar(32) NOT NULL DEFAULT 'EN_CURSO' CHECK(estado IN('EN_CURSO','COMPLETADO','ERROR')),
  dimensiones integer NOT NULL DEFAULT 0,
  matriculas integer NOT NULL DEFAULT 0,
  resultados integer NOT NULL DEFAULT 0,
  pagos integer NOT NULL DEFAULT 0,
  detalle jsonb NOT NULL DEFAULT '{}'
);
CREATE INDEX etl_ejecuciones_inicio_idx ON dw.etl_ejecuciones(inicio);

CREATE VIEW dw.v_matriculas_por_gestion_carrera AS
SELECT g.gestion_id,g.nombre AS gestion,c.carrera_id,c.nombre AS carrera,
       count(*)::integer AS total,count(DISTINCT f.estudiante_id)::integer AS estudiantes,
       sum(CASE WHEN f.estado='ACTIVA' THEN f.cantidad ELSE 0 END)::integer AS activas
FROM dw.fact_matriculas f
JOIN dw.dim_gestion g ON g.gestion_id=f.gestion_id
JOIN dw.dim_carrera c ON c.carrera_id=f.carrera_id
GROUP BY g.gestion_id,g.nombre,c.carrera_id,c.nombre;

CREATE VIEW dw.v_rendimiento_por_carrera AS
SELECT g.gestion_id,g.nombre AS gestion,c.carrera_id,c.nombre AS carrera,
       count(*)::integer AS inscripciones,sum(f.aprobado)::integer AS aprobados,
       round(avg(f.nota_final),2) AS promedio,
       round(avg(f.asistencia),2) AS asistencia_promedio,
       round(100.0*sum(f.aprobado)/nullif(count(*),0),2) AS tasa_aprobacion
FROM dw.fact_resultados f
JOIN dw.dim_gestion g ON g.gestion_id=f.gestion_id
JOIN dw.dim_carrera c ON c.carrera_id=f.carrera_id
GROUP BY g.gestion_id,g.nombre,c.carrera_id,c.nombre;

CREATE VIEW dw.v_recaudacion_mensual AS
SELECT to_char(t.fecha,'YYYY-MM') AS mes,t.anio,t.mes AS mes_numero,t.mes_nombre,
       g.gestion_id,g.nombre AS gestion,
       c.carrera_id,c.nombre AS carrera,count(*)::integer AS pagos,sum(f.monto) AS total
FROM dw.fact_pagos f
JOIN dw.dim_tiempo t ON t.fecha=f.fecha
JOIN dw.dim_gestion g ON g.gestion_id=f.gestion_id
JOIN dw.dim_carrera c ON c.carrera_id=f.carrera_id
GROUP BY to_char(t.fecha,'YYYY-MM'),t.anio,t.mes,t.mes_nombre,g.gestion_id,g.nombre,c.carrera_id,c.nombre;
